"""Regenerate the firmware constants from the contract used directly by the app."""
import json
import sys
from pathlib import Path
from uuid import UUID

root = Path(__file__).resolve().parents[1]
data = json.loads((root / 'shared/radar-v1.json').read_text(encoding='utf-8'))
assert [t['id'] for t in data['tags']] == list(range(1, len(data['tags']) + 1))
lines = ['/* Generated by scripts/generate_protocol.py; edit shared/radar-v1.json. */', '#ifndef RADAR_DICTIONARY_H', '#define RADAR_DICTIONARY_H',
         f'#define RADAR_DICTIONARY_VERSION {data["dictionaryVersion"]}',
         f'#define RADAR_TAG_MASK 0x{((1 << len(data["tags"])) - 1):04x}u']
for name, key in [('SERVICE','serviceUuid'),('WRITE','writeUuid'),('NOTIFY','notifyUuid')]:
    values = ', '.join(f'0x{x:02x}' for x in UUID(data[key]).bytes[::-1])
    lines.append(f'#define RADAR_{name}_UUID_BYTES {values}')
lines += ['#endif', '']
output = root / 'firmware/include/radar_dictionary.h'
content = '\n'.join(lines)
if '--check' in sys.argv:
    assert output.read_text(encoding='utf-8') == content, 'Generated firmware dictionary is out of date'
    print('Shared dictionary and firmware constants agree.')
else:
    output.write_text(content, encoding='utf-8', newline='\n')
    print(output)
